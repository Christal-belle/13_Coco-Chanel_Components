      <blockquote class="mt-10 text-2xl/9 font-medium tracking-tight text-balance text-neutral-950 sm:text-3xl/10 lg:text-4xl/12 dark:text-neutral-50">
         <p>Perancang busana Coco Chanel lahir dengan nama Gabrielle Bonheur Chanel pada 19
Agustus 1883 di Saumur Perancis. Dia lahir dalam kemiskinan dari dua orangtua yang tidak
menikah.
Setelah ibunya meninggal dunia, sang ayah menyerahkannya ke panti asuhan.
Dia dibesarkan oleh biarawati yang mengajarkannya menjahit pakaian, kemampuan itu kelak
mengantarnya sebagai ikon mode.
Tak hanya punya keterampilan menjahit, Chanel juga memiliki bakat menyanyi. Dia sempat
menggunakan kepiawaiannya dalam bernyanyi untuk mencari uang.
Mengadu nasib sebagai penyanyi kafe, dia memperoleh nama sapaan "Coco".
The Atlantic menulis, nama tersebut diambil dari kependekan kata "cocotte" yang pernah
diucapkan oleh Chanel. Cocotte merupakan kata dalam bahasa Perancis yang berarti wanita
simpanan.
Sekitar usia 20 tahun, Chanel bertemu dengan Etienne Balsan, yang menawarkan bantuan
untuk memulai bisnis topi perempuan di Paris.
Namun, Chanel kemudian meninggalkannya dan memilih bergabung dengan temannya yang
lebih kaya, Arthur "Boy" Capel. Balsan dan Capel merupakan dua pria yang berperan dalam
usaha mode pertama Chanel.
Membuka toko pertamanya di Paris's Rue Cambon pada 1910, Chanel mulai menjual topi.
Terus berkembang dengan menambah dua toko di Deaville dan Biarritz, Chanel mengawali
bisnis fesyennya.
"Kemewahan haruslah nyaman. Jika tidak, itu bukan kemewahan," kutipan kondangnya yang
menjadi dasar dia merancang busana.
Desain Coco menekankan pada kesederhanaan dan kenyamanan sehingga merombak industri
fesyen.
Pada akhir 1920-an, rumah mode Chanel dilaporkan bernilai jutaan dollar dan memiliki
karyawan lebih dari 2.000 orang, yang tak hanya terdiri dari modiste, tapi juga pekerja di
laboratorium parfumnya, pabrik tekstil, dan pengrajin perhiasan.
Bisnis raksasanya makin menanjak ketika dia merilis parfum Chanel No.5 pada 1922, yang
harganya kini sekitar Rp 1,3 juta untuk ukuran 50 ml.
Dengan bantuan dari Ernst Beauz, seorang pembuat parfum terkenal di Perancis, Chanel
memilih sampel nomor lima, perpaduan dari melati dan beberapa wangi-wangian bunga.
Selain itu, rancangan gaun hitam sederhana Chanel. Dia membuktikan busana berwarna
hitam identik dengan suasana berkabung bisa modis dipakai untuk gaun malam.
Chanel sempat menutup rumah modenya pada 1939 karena meletusnya Perang Dunia II.
Hubungannya dengan seorang diplomat Jerman selama masa pendudukan Jerman,
menurunkan reputasinya. Dia berhenti dari dunia fesyen sampai 1954.
Pada usia 70 tahun, Chanel kembali ke dunia mode. Dia pertama kali menerima ulasan pedas
dari para kritikus, tetapi desainnya yang feminin dan mudah dikenakan justru memenangkan
hati pecinta mode di seluruh dunia.
Coco Chanel wafat pada 10 Januari 1971 di apartemennya di Hotel Ritz. Dia tidak pernah
menikah.
Ratusan orang berdesakan di Gereja Madeleine untuk mengucapkan selamat tinggal pada
ikon fesyen. Sebagai penghargaan, banyak dari pelayat yang mengenakan pakaian Chanel.
Hari ini perusahaan Coco Chanel dipegang secara pribadi oleh keluarga Wertheimer dan terus
berkembang dengan penjualan ratusan juta dollar setiap tahun.</blockquote>
